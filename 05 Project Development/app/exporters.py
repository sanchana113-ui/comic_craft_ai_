import os
import re
import time
from fpdf import FPDF

EXPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "static", "exports")
os.makedirs(EXPORTS_DIR, exist_ok=True)


def _sanitize_pdf_text(text: str) -> str:
    """Replaces smart quotes and unicode symbols not supported by standard PDF fonts."""
    if not text:
        return ""
    replacements = {
        "“": '"', "”": '"', "‘": "'", "’": "'",
        "—": " - ", "–": " - ", "…": "...",
        "\u201c": '"', "\u201d": '"', "\u2018": "'", "\u2019": "'",
        "\u2014": " - ", "\u2013": " - ", "\u2026": "..."
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    # Filter to latin-1 encodable characters for standard Helvetica/Arial font
    return text.encode("latin-1", "replace").decode("latin-1")


class ComicPDF(FPDF):
    """Custom FPDF subclass with comic styling."""

    def __init__(self, title_text="ComicCraft Comic", *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.comic_title = _sanitize_pdf_text(title_text)

    def header(self):
        if self.page_no() > 1:
            self.set_font("helvetica", "B", 8)
            self.set_text_color(120, 120, 120)
            self.cell(0, 7, f"ComicCraft  |  {self.comic_title}", border=0, align="L")
            self.cell(0, 7, f"Page {self.page_no()}", border=0, align="R", new_x="LMARGIN", new_y="NEXT")
            self.set_draw_color(220, 220, 220)
            self.set_line_width(0.3)
            self.line(10, 14, 200, 14)
            self.ln(3)

    def footer(self):
        self.set_y(-12)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(140, 140, 140)
        self.cell(0, 10, "Generated by ComicCraft AI - Powered by Google Gemini & Stable Diffusion", border=0, align="C")


def save_pdf(layout: list, comic_title: str = "ComicCraft Comic", character_name: str = "Hero", setting: str = "World", tone: str = "Dramatic", art_style: str = "Comic Book") -> str:
    """
    Compiles the full comic into a multi-page PDF using FPDF2.
    Each panel's image and narration are placed neatly on separate pages.
    Saves to static/exports and returns the relative path.
    """
    timestamp = int(time.time())
    safe_title = re.sub(r"[^\w\-]", "_", comic_title).strip("_") or "comic"
    filename = f"{safe_title}_{timestamp}.pdf"
    filepath = os.path.join(EXPORTS_DIR, filename)

    pdf = ComicPDF(title_text=comic_title, orientation="P", unit="mm", format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)

    # ------------------ COVER PAGE ------------------
    pdf.add_page()
    pdf.set_margins(15, 15, 15)

    # Decorative Cover Frame
    pdf.set_draw_color(220, 50, 40)
    pdf.set_line_width(1.5)
    pdf.rect(10, 10, 190, 277)
    pdf.set_draw_color(30, 30, 30)
    pdf.set_line_width(0.5)
    pdf.rect(12, 12, 186, 273)

    # Main Banner
    pdf.ln(12)
    pdf.set_fill_color(230, 45, 40)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font("helvetica", "B", 14)
    pdf.cell(180, 10, "COMICCRAFT AI PRESENTATION", fill=True, align="C", new_x="LMARGIN", new_y="NEXT")

    pdf.ln(18)
    pdf.set_text_color(20, 20, 30)
    pdf.set_font("helvetica", "B", 24)
    pdf.multi_cell(180, 12, _sanitize_pdf_text(comic_title), align="C")

    pdf.ln(6)
    pdf.set_font("helvetica", "I", 12)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(180, 8, "An Original AI-Generated Comic Book Story", align="C", new_x="LMARGIN", new_y="NEXT")

    # Cover Thumbnail (Panel 1 image if available)
    if layout and len(layout) > 0:
        first_img = layout[0].get("image_path", "")
        # Resolve path
        if first_img.startswith("/"):
            first_img = first_img[1:]
        abs_img_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), first_img)
        if os.path.exists(abs_img_path):
            pdf.ln(6)
            cover_img_w = 140
            cover_img_x = (210 - cover_img_w) / 2
            pdf.image(abs_img_path, x=cover_img_x, y=pdf.get_y(), w=cover_img_w)
            pdf.set_y(pdf.get_y() + 96)

    # Story Parameters Box
    pdf.ln(6)
    pdf.set_fill_color(248, 248, 252)
    pdf.set_draw_color(200, 200, 215)
    pdf.set_line_width(0.3)
    curr_y = pdf.get_y()
    pdf.rect(20, curr_y, 170, 38, style="FD")

    pdf.set_xy(25, curr_y + 4)
    pdf.set_font("helvetica", "B", 10)
    pdf.set_text_color(50, 50, 60)
    pdf.cell(80, 7, f"Main Character: {_sanitize_pdf_text(character_name or 'The Hero')}")
    pdf.cell(80, 7, f"Setting: {_sanitize_pdf_text(setting or 'Enchanted Forest')}", new_x="LMARGIN", new_y="NEXT")

    pdf.set_x(25)
    pdf.cell(80, 7, f"Story Tone: {_sanitize_pdf_text(tone or 'Dramatic')}")
    pdf.cell(80, 7, f"Art Style: {_sanitize_pdf_text(art_style or 'Comic Book')}", new_x="LMARGIN", new_y="NEXT")

    pdf.set_x(25)
    pdf.set_font("helvetica", "I", 9)
    pdf.set_text_color(100, 100, 110)
    pdf.cell(160, 7, f"Panels: {len(layout)} Complete Story Panels  |  Format: Sequential Graphic Story")

    # ------------------ PANEL PAGES ------------------
    for panel in layout:
        pdf.add_page()
        pdf.set_margins(15, 15, 15)

        panel_num = panel.get("panel_number", 1)
        title = _sanitize_pdf_text(panel.get("title", f"Panel {panel_num}"))
        scene_desc = _sanitize_pdf_text(panel.get("scene_description", ""))
        caption = _sanitize_pdf_text(panel.get("caption", ""))
        narration = _sanitize_pdf_text(panel.get("narration", ""))
        dialogue = _sanitize_pdf_text(panel.get("dialogue", ""))
        img_rel_path = panel.get("image_path", "")

        # Header Title
        pdf.set_fill_color(20, 25, 35)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("helvetica", "B", 13)
        pdf.cell(180, 9, f"  {title.upper()}", fill=True, align="L", new_x="LMARGIN", new_y="NEXT")

        pdf.ln(3)

        # Panel Image
        if img_rel_path.startswith("/"):
            img_rel_path = img_rel_path[1:]
        abs_img_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), img_rel_path)

        if os.path.exists(abs_img_path):
            img_w = 170
            img_x = (210 - img_w) / 2
            curr_img_y = pdf.get_y()
            pdf.image(abs_img_path, x=img_x, y=curr_img_y, w=img_w)
            pdf.set_y(curr_img_y + 115)
        else:
            pdf.ln(10)
            pdf.set_fill_color(235, 235, 240)
            pdf.rect(20, pdf.get_y(), 170, 40, style="F")
            pdf.set_font("helvetica", "I", 10)
            pdf.set_text_color(100, 100, 100)
            pdf.cell(180, 40, "[Panel Illustration]", align="C", new_x="LMARGIN", new_y="NEXT")

        pdf.ln(4)

        # Scene Description Callout (Italics)
        if scene_desc:
            pdf.set_fill_color(245, 245, 248)
            pdf.set_draw_color(210, 210, 220)
            pdf.set_line_width(0.2)
            desc_y = pdf.get_y()
            pdf.set_font("helvetica", "I", 10)
            pdf.set_text_color(70, 70, 80)
            pdf.multi_cell(180, 6, f"Scene: {scene_desc}", fill=True, border=1)
            pdf.ln(3)

        # Ambient Caption (Yellow comic caption box)
        if caption:
            pdf.set_fill_color(255, 250, 205)
            pdf.set_draw_color(180, 170, 100)
            pdf.set_line_width(0.3)
            pdf.set_font("helvetica", "B", 9)
            pdf.set_text_color(80, 60, 10)
            pdf.multi_cell(180, 6, f"CAPTION: {caption}", fill=True, border=1)
            pdf.ln(3)

        # Narration & Character Dialogue
        if narration or dialogue:
            pdf.set_fill_color(255, 255, 255)
            pdf.set_draw_color(40, 40, 50)
            pdf.set_line_width(0.4)

            if narration:
                pdf.set_font("helvetica", "", 10)
                pdf.set_text_color(30, 30, 35)
                pdf.multi_cell(180, 6, narration)
                pdf.ln(2)

            if dialogue:
                pdf.set_fill_color(240, 248, 255)
                pdf.set_draw_color(100, 150, 210)
                pdf.set_font("helvetica", "B", 10)
                pdf.set_text_color(20, 40, 90)
                pdf.multi_cell(180, 6, f"Dialogue: {dialogue}", fill=True, border=1)

    pdf.output(filepath)
    print(f"[ComicCraft] PDF successfully exported to: {filepath}")
    return f"/static/exports/{filename}"
